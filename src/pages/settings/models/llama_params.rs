pub fn by_key(key: &str) -> Option<&'static LlamaParam> {
    LLAMA_PARAMS.iter().find(|p| p.key == key)
}

pub fn params_in_category(cat: ParamCategory) -> impl Iterator<Item = &'static LlamaParam> {
    LLAMA_PARAMS.iter().filter(move |p| p.category == cat)
}

/// Дефолтное `ParamValue` для чипа при добавлении — соответствует `kind.default`.
pub fn default_value(kind: &ParamKind) -> crate::config::ParamValue {
    use crate::config::ParamValue;
    match kind {
        ParamKind::Int { default, .. } => ParamValue::Int(*default),
        ParamKind::Float { default, .. } => ParamValue::Float(*default),
        ParamKind::Bool { default } => ParamValue::Bool(*default),
        ParamKind::Text { default } => ParamValue::Text((*default).to_string()),
        ParamKind::Enum { default, .. } => ParamValue::Enum((*default).to_string()),
    }
}
