//! Системный промпт агента Syn-чата.
//!
//! До этого модуля Syn-чат уходил в генерацию вообще без system-сообщения:
//! `AppConfig::syn_chat_system_prompt` по умолчанию пуст, а `build_history`
//! пустую строку не добавляет. Модель с `bash` в руках работала без роли, без
//! окружения и — главное — без критерия остановки. В сохранённых чатах это
//! видно буквально: agent-loop уходил в сотню одинаковых вызовов подряд.
//!
//! Пользовательский промпт из настроек базовые правила не заменяет, а
//! дописывается к ним: правила работы с инструментами — часть контракта
//! agent-loop'а (guard повторов, лимит ходов), терять их из-за того, что
//! пользователь вписал в поле «отвечай в рифму», нельзя.
//!
//! Важно для префикс-KV: промпт должен быть стабилен между сообщениями
//! одного чата — он лежит в самой голове контекста, и любое изменение
//! обнуляет переиспользование кэша. Поэтому здесь есть дата, но нет времени.

use crate::agent::time::format_date_today;

/// Данные окружения для промпта. Собираются на main-потоке (нужен доступ к
/// сигналам активных инструментов), сам рендер — чистая функция.
pub struct PromptEnv {
    /// Дата «YYYY-MM-DD». Время намеренно не включаем (см. модульный док).
    pub date: String,
    /// ОС/платформа — модель должна понимать, какие команды доступны.
    pub os: String,
    /// Рабочий каталог процесса: `bash -lc` стартует именно в нём.
    pub cwd: String,
    /// Лейблы активных инструментов в порядке каталога.
    pub tools: Vec<String>,
    /// Лимит ходов agent-loop'а на одно сообщение («Глубина основного агента»).
    pub max_turns: usize,
    /// Пользовательский промпт из настроек. Пустой — просто не добавляется.
    pub user_prompt: String,
}

impl PromptEnv {
    /// Снимок окружения процесса. Инструменты и лимит ходов передаёт
    /// вызывающий — они живут в сигналах `AppCtx`.
    pub fn snapshot(tools: Vec<String>, max_turns: usize, user_prompt: String) -> Self {
        Self {
            date: format_date_today(),
            os: format!("{} ({})", std::env::consts::OS, std::env::consts::ARCH),
            cwd: std::env::current_dir()
                .map(|p| p.display().to_string())
                .unwrap_or_else(|_| "неизвестен".to_string()),
            tools,
            max_turns,
            user_prompt,
        }
    }
}

/// Собрать итоговый system-промпт.
pub fn build(env: &PromptEnv) -> String {
    let mut s = String::with_capacity(1024);
    s.push_str(
        "Ты — Syn, локальный AI-агент в приложении Synthos. Работаешь на \
         машине пользователя, отвечаешь на его языке.\n\n",
    );

    s.push_str("Окружение:\n");
    s.push_str(&format!("- сегодня: {}\n", env.date));
    s.push_str(&format!("- система: {}\n", env.os));
    s.push_str(&format!("- рабочий каталог: {}\n", env.cwd));

    if env.tools.is_empty() {
        s.push_str(
            "- инструменты выключены: отвечай по своим знаниям и честно \
             говори, когда данных не хватает.\n",
        );
    } else {
        s.push_str(&format!("- доступные инструменты: {}\n", env.tools.join(", ")));
        s.push_str(&format!(
            "\nПравила работы с инструментами (бюджет — {} ходов на одно \
             сообщение пользователя):\n",
            env.max_turns
        ));
        s.push_str(
            "1. Каждый вызов должен давать новый факт. Не повторяй вызов, \
             который уже делал в этом диалоге: результат будет тот же, а ход \
             потрачен.\n\
             2. Не получилось — меняй подход: другая команда, другой путь, \
             другой инструмент. Повтор того же самого — тупик, а не попытка.\n\
             3. Опирайся на результаты, которые уже есть выше в диалоге; \
             перечитывать одно и то же не нужно.\n\
             4. Как только данных хватает для ответа — прекращай вызовы и \
             отвечай текстом. Разведка «про запас» тратит бюджет ходов.\n\
             5. Если задача не решается доступными средствами — так и скажи: \
             что выяснил, где уперся, что предлагаешь дальше. Молча ходить по \
             кругу нельзя.\n\
             6. Перед необратимым действием (изменение или удаление файлов, \
             установка пакетов, сетевые запросы с побочными эффектами) в одном \
             предложении скажи, что собираешься сделать.\n",
        );
        // Правила пайплайнов — только когда инструмент активен: текст
        // зависит лишь от набора инструментов (как и строка со списком),
        // поэтому префикс-KV между сообщениями не страдает.
        if env.tools.iter().any(|t| t == "pipelines") {
            s.push_str(
                "\nПайплайны (`pipelines`) — генерация видео/музыки/речи в \
                 нодовом редакторе:\n\
                 - Порядок: list → open (шаблон) → nodes с filter (точная \
                 схема нужных нод) → apply (промпты, параметры, ref-входы) → \
                 run. Сценарий/промпт сочиняй сам и клади в state нод.\n\
                 - nodes: в filter перечисляй сами ноды (через пробел), а не \
                 имена полей — поля видны в примере state. Промах фильтра \
                 вернёт список видов нод: бери имена оттуда, а не подбирай.\n\
                 - Перед тяжёлым прогоном (LTX, MiniMax-H3) проверь `system \
                 status`: если модели пайплайна не влезают рядом с тобой — \
                 запускай run с free_vram=true (тебя выгрузят на время \
                 прогона и вернут; истории это не вредит).\n\
                 - run блокирует ход до конца прогона и может идти десятки \
                 минут — это нормально, пользователь видит живой статус. \
                 Результаты (видео/аудио) сами прикладываются к сообщению.\n\
                 - Пути к моделям не выдумывай: инвентарь каталогов (основной \
                 и кэш HF) есть в pipelines list — разделы «Модели в каталоге»; \
                 пустые model_path чекпойнтов заполняй через apply set_state \
                 до run. Числовые `*_idx`-поля state (квант, device, aspect) \
                 расшифрованы в action=nodes под примером state.\n\
                 - Повторный запуск того же графа — с новым run_id.\n\
                 - Ref-картинки из чата подключай ссылкой \
                 attachment:<имя|sha|last> в путях state (список — в \
                 pipelines list).\n",
            );
        }
    }

    s.push_str(
        "\nОтвет: по делу, без воды и без пересказа собственных действий \
         шаг за шагом. Код и пути — точными, как в источнике.",
    );

    let extra = env.user_prompt.trim();
    if !extra.is_empty() {
        s.push_str("\n\nДополнительные указания пользователя:\n");
        s.push_str(extra);
    }
    s
}

/// Заметка про остаток бюджета ходов. Дописывается к результату инструмента
/// (а не в system-сообщение) намеренно: system лежит в голове контекста, и
/// правка на каждом ходу обнуляла бы префикс-KV, а хвост промпта и так
/// пересчитывается.
pub fn budget_note(turns_left: usize) -> String {
    format!(
        "\n\n[Системная заметка: осталось ходов агента — {turns_left}. \
         Сворачивай работу и дай текстовый ответ по тому, что уже известно.]"
    )
}

/// Порог, начиная с которого к результатам инструментов дописывается
/// [`budget_note`]. Раньше смысла нет: заметка на каждом ходу — это шум.
pub const BUDGET_NOTE_FROM: usize = 3;

#[cfg(test)]
mod tests {
    use super::*;

    fn env() -> PromptEnv {
        PromptEnv {
            date: "2026-08-19".to_string(),
            os: "linux (x86_64)".to_string(),
            cwd: "/home/u/proj".to_string(),
            tools: vec!["bash".to_string(), "web".to_string()],
            max_turns: 32,
            user_prompt: String::new(),
        }
    }

    #[test]
    fn build_includes_environment_and_rules() {
        let s = build(&env());
        assert!(s.contains("2026-08-19"));
        assert!(s.contains("/home/u/proj"));
        assert!(s.contains("bash, web"));
        assert!(s.contains("32 ходов"));
        assert!(s.contains("Не повторяй вызов"));
    }

    #[test]
    fn build_has_no_clock_time_for_prefix_kv_stability() {
        // Промпт лежит в голове контекста: любое ежеминутно меняющееся поле
        // обнуляло бы переиспользование префикс-KV между сообщениями.
        let s = build(&env());
        assert!(!s.contains(':') || !s.contains("время"));
        assert!(!s.to_lowercase().contains("время:"));
    }

    #[test]
    fn build_without_tools_drops_tool_rules() {
        let mut e = env();
        e.tools.clear();
        let s = build(&e);
        assert!(s.contains("инструменты выключены"));
        assert!(!s.contains("Не повторяй вызов"));
    }

    #[test]
    fn user_prompt_is_appended_not_replacing() {
        let mut e = env();
        e.user_prompt = "  Отвечай кратко.  ".to_string();
        let s = build(&e);
        assert!(s.contains("Не повторяй вызов"));
        assert!(s.trim_end().ends_with("Отвечай кратко."));
    }

    #[test]
    fn budget_note_mentions_remaining_turns() {
        assert!(budget_note(2).contains("осталось ходов агента — 2"));
    }

    #[test]
    fn pipeline_rules_only_with_pipelines_tool() {
        let s = build(&env());
        assert!(!s.contains("Пайплайны"));
        let mut e = env();
        e.tools.push("pipelines".to_string());
        let s = build(&e);
        assert!(s.contains("Пайплайны"));
        assert!(s.contains("free_vram"));
        assert!(s.contains("attachment:"));
    }
}
