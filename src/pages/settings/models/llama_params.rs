/// Тип контрола и вспомогательные метаданные для spin-box/toggle/dropdown.
#[derive(Clone, Copy, Debug)]
pub enum ParamKind {
    /// Целое число.
    Int { min: i64, max: i64, step: i64, default: i64 },
    /// Число с плавающей точкой.
    Float { min: f64, max: f64, step: f64, default: f64, decimals: u8 },
    /// Булевый флаг (on/off).
    Bool { default: bool },
    /// Текст (путь, имя, произвольная строка).
    Text { default: &'static str },
    /// Выбор из фиксированного набора.
    Enum {
        options: &'static [&'static str],
        default: &'static str,
    },
}

/// Описание одного параметра llama-server.
#[derive(Clone, Copy, Debug)]
pub struct LlamaParam {
    pub key: &'static str,
    pub cli: &'static str,
    pub aliases: &'static [&'static str],
    pub label: &'static str,
    pub description: &'static str,
    pub category: ParamCategory,
    pub kind: ParamKind,
    pub removable: bool,
    pub env: Option<&'static str>,
}

const fn int(min: i64, max: i64, step: i64, default: i64) -> ParamKind {
    ParamKind::Int { min, max, step, default }
}
const fn float(min: f64, max: f64, step: f64, decimals: u8, default: f64) -> ParamKind {
    ParamKind::Float { min, max, step, default, decimals }
}
const fn bool_k(default: bool) -> ParamKind {
    ParamKind::Bool { default }
}
const fn text_k(default: &'static str) -> ParamKind {
    ParamKind::Text { default }
}
const fn enum_k(options: &'static [&'static str], default: &'static str) -> ParamKind {
    ParamKind::Enum { options, default }
}

