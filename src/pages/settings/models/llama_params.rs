/// Мелкий helper-макрос, чтобы писать записи компактно, без повтора полей по умолчанию.
macro_rules! lp {
    (
        key: $key:expr,
        cli: $cli:expr,
        $( aliases: $al:expr, )?
        label: $lbl:expr,
        description: $desc:expr,
        category: $cat:expr,
        kind: $kind:expr
        $(, env: $env:expr )?
        $(, removable: $rm:expr )?
        $(,)?
    ) => {
        LlamaParam {
            key: $key,
            cli: $cli,
            aliases: lp!(@aliases $( $al )? ),
            label: $lbl,
            description: $desc,
            category: $cat,
            kind: $kind,
            removable: lp!(@rm $( $rm )? ),
            env: lp!(@env $( $env )? ),
        }
    };
    (@aliases $al:expr) => { $al };
    (@aliases)          => { &[] };
    (@rm $rm:expr) => { $rm };
    (@rm)          => { true };
    (@env $env:expr) => { Some($env) };
    (@env)           => { None };
}

